# 便捷入口
# ============================================================
async def heal_failure(
    failure: FailureContext,
    *,
    retry_budget: int = 3,
) -> tuple[HealResult, dict]:
    """
    一键自愈 + 自动开 PR

    Returns:
        (heal_result, pr_result)

    Usage:
        result, pr = await heal_failure(
            FailureContext(test_id="login_001", ...),
            retry_budget=3,
        )
        if result.success:
            print(f"Healed via {result.strategy}, PR: {pr['url']}")
    """
    engine = SelfHealEngine(retry_budget=retry_budget)
    result = await engine.heal(failure)

    pr_result = {}
    if result.success:
        pr_result = await engine.commit_fix(result)

    return result, pr_result


