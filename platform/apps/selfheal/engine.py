"""
自愈引擎：五段闭环

1. 规则修复 (Flash low)   - 超时重试、等待条件、网络抖动
2. 向量定位器库 (Flash low) - 从历史成功定位器中找相似
3. LLM 候选 (Flash high)  - 分析失败截图/日志生成修复
4. 重跑验证 (MCP)          - 执行修复后代码
5. 开 PR (Git MCP)         - 自动提交修复

这是 WHartTest 唯一没做好的部分 → 你的核心差异化。
"""
import asyncio
import json
from dataclasses import dataclass, field
from typing import Optional
from apps.agent.router import route, get_cost_tracker
from apps.mcp.client import MCPClient


@dataclass
class HealResult:
    """自愈结果"""
    success: bool
    strategy: str              # "rule" / "vector" / "llm"
    old_locator: str
    new_locator: Optional[str] = None
    confidence: float = 0.0
    retries: int = 0
    error: Optional[str] = None


@dataclass
class FailureContext:
    """失败上下文"""
    test_id: str
    error_message: str
    stack_trace: str
    screenshot_path: Optional[str] = None
    page_url: Optional[str] = None
    html_snippet: Optional[str] = None
    locator: Optional[str] = None


class SelfHealEngine:
    """
    自愈引擎

    Usage:
        engine = SelfHealEngine(retry_budget=3)
        result = await engine.heal(failure)
        if result.success:
            await engine.commit_fix(result)  # 开 PR
    """

    def __init__(self, retry_budget: int = 3):
        self.retry_budget = retry_budget
        self.cost_tracker = get_cost_tracker()

    async def heal(self, failure: FailureContext) -> HealResult:
        """
        执行五段自愈闭环

        成本保护：超过 retry_budget 立即放弃，防止无限循环
        """
        for attempt in range(self.retry_budget):
            # ---- Step 1: 规则修复 (Flash low, 最快最便宜) ----
            result = await self._rule_based_fix(failure)
            if result and result.success:
                result.strategy = "rule"
                result.retries = attempt + 1
                return result

            # ---- Step 2: 向量定位器库 (Flash low) ----
            result = await self._vector_locator_lookup(failure)
            if result and result.success:
                result.strategy = "vector"
                result.retries = attempt + 1
                return result

            # ---- Step 3: LLM 候选生成 (Flash high, 深度思考) ----
            result = await self._llm_candidate(failure)
            if not result:
                continue

            # ---- Step 4: 重跑验证 (MCP) ----
            verified = await self._verify_fix(result, failure)
            if verified:
                result.strategy = "llm"
                result.retries = attempt + 1
                return result

        # 超过预算，放弃
        return HealResult(
            success=False,
            strategy="exhausted",
            old_locator=failure.locator or "",
            error=f"Retry budget ({self.retry_budget}) exhausted",
        )

    async def commit_fix(self, result: HealResult, *, branch: str = None) -> dict:
        """
        Step 5: 自动开 PR (Git MCP)
        将修复后的定位器写入代码并提交
        """
        if not result.success or not result.new_locator:
            return {"status": "skipped"}

        import os
        from pathlib import Path

        # 确定修复文件 (约定: tests/locators/{test_id}.py)
        locator_file = Path(f"tests/locators/{result.test_id}.py")
        locator_file.parent.mkdir(parents=True, exist_ok=True)

        content = f'''# Auto-generated by SelfHealEngine
# Strategy: {result.strategy}
# Confidence: {result.confidence}

LOCATORS = {{
    "original": "{result.old_locator}",
    "healed": "{result.new_locator}",
}}
'''

        branch = branch or f"self-heal/{result.test_id}"

        async with MCPClient() as mcp:
            # 创建分支 + 提交
            await mcp.call_tool("git", "create_branch", {"branch": branch})
            await mcp.call_tool("git", "commit_changes", {
                "files": {str(locator_file): content},
                "message": f"fix(locator): self-heal {result.test_id} via {result.strategy}",
            })
            # 开 PR
            pr = await mcp.call_tool("git", "create_pull_request", {
                "title": f"[Self-Heal] Fix locator in {result.test_id}",
                "body": (
                    f"Auto-generated by SelfHealEngine\n\n"
                    f"- Strategy: {result.strategy}\n"
                    f"- Confidence: {result.confidence}\n"
                    f"- Retries: {result.retries}\n"
                ),
                "branch": branch,
            })

        return {"status": "pr_created", "branch": branch, "pr": pr}

    # ============================================================
    # 五段闭环的具体实现
    # ============================================================

    async def _rule_based_fix(self, failure: FailureContext) -> Optional[HealResult]:
        """
        Step 1: 规则修复 (Flash low)

        常见模式：
        - TimeoutError → 增加等待时间
        - ElementNotVisible → scrollIntoView
        - NetworkError → 重试 (幂等)
        - StaleElementReference → 重新查询
        """
        cfg = route("refine_locator")  # Flash (low)
        # 记录成本
        self.cost_tracker.record(100, 50)

        error = failure.error_message.lower()

        # 超时 → 等待策略
        if "timeout" in error:
            return HealResult(
                success=True,
                strategy="rule",
                old_locator=failure.locator or "",
                new_locator=f"{failure.locator} (wait_for_visible, timeout=10000)",
                confidence=0.7,
            )

        # 元素不可见 → 滚动
        if "not visible" in error or "element not interactable" in error:
            return HealResult(
                success=True,
                strategy="rule",
                old_locator=failure.locator or "",
                new_locator=f"scroll_into_view({failure.locator})",
                confidence=0.6,
            )

        # Stale element → 重新获取
        if "stale" in error:
            return HealResult(
                success=True,
                strategy="rule",
                old_locator=failure.locator or "",
                new_locator=f"page.reload().find({failure.locator})",
                confidence=0.5,
            )

        return None  # 不匹配任何规则，进入下一步

    async def _vector_locator_lookup(self, failure: FailureContext) -> Optional[HealResult]:
        """
        Step 2: 向量定位器库 (Flash low)

        从 Qdrant 检索历史成功的定位器：
        - 相同页面 URL + 相似元素描述 → 推荐定位器
        - 基于 text/role/position 的语义相似度
        """
        cfg = route("refine_locator")  # Flash (low)
        self.cost_tracker.record(200, 100)

        # 从 Qdrant 检索相似定位器
